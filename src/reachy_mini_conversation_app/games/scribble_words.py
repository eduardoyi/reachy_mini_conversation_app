    """One word to draw: its names, its category key, and every form that counts as guessed."""

    es: str
    en: str
    category: str
    accept: tuple[str, ...]

    def name(self, language: str) -> str:
        """Return the word as the drawer sees it."""
        return self.es if language == "es" else self.en


