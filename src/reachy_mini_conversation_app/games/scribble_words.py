def _parse(lists: dict[str, tuple[str, ...]], level: str = "") -> tuple[Word, ...]:
    words: list[Word] = []
    for category, entries in lists.items():
        for entry in entries:
            spanish, english = (side.split(";") for side in entry.split(" / "))
            forms = [form.strip() for form in (*spanish, *english) if form.strip()]
            words.append(Word(spanish[0].strip(), english[0].strip(), category, tuple(dict.fromkeys(forms)), level))
    return tuple(words)


