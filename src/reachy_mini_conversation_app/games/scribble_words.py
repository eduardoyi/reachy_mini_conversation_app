"""Scribble Rush's words: a kids' list (things a 4-year-old can draw) and an adults' list, by category.

Each entry is "Spanish forms / English forms" (forms separated by ";"), the first of each the word the drawer sees; every form, in either
language, counts when Richie guesses it. Adults also draw actions, films, places and Venezuelan sayings, each a
picture of one or two drawable ideas (a sleeping shrimp for "camarón que se duerme"); a saying's picture counts.
Adults' wackier categories (absurd scenes, everyday disasters, monsters, inventions, pop culture)
hinge on one or two drawable ideas; a scene's forms keep the articles a guess would say ("pulpo en una patineta")
and never name one of its nouns alone, so "un pulpo" does not count for "pulpo en patineta". Each adult word has a
level, easy, medium or hard: how hard it is to draw in 20 seconds and for Richie to recognise; a team draws harder
words as it climbs the track. Venezuelan-only words wait in ``VENEZUELAN_WORDS`` for a Venezuelan edition.
"""

from typing import Final
from dataclasses import dataclass


@dataclass(frozen=True)
class Word:
    """One word to draw: its names, its category key, every form that counts as guessed, and its level (adults)."""

    es: str
    en: str
    category: str
    accept: tuple[str, ...]
    level: str = ""

    def name(self, language: str) -> str:
        """Return the word as the drawer sees it."""
        return self.es if language == "es" else self.en


