def category_name(category: str, language: str) -> str:
    """Return a category's name in ``language``."""
    spanish, english = CATEGORIES[category]
    return spanish if language == "es" else english


def _parse(lists: dict[str, tuple[str, ...]]) -> tuple[Word, ...]:
    words: list[Word] = []
    for category, entries in lists.items():
        for entry in entries:
            spanish, english = (side.split(";") for side in entry.split(" / "))
            forms = [form.strip() for form in (*spanish, *english) if form.strip()]
            words.append(Word(spanish[0].strip(), english[0].strip(), category, tuple(dict.fromkeys(forms))))
    return tuple(words)


KIDS_WORDS: Final[tuple[Word, ...]] = _parse(_KIDS)
ADULT_WORDS: Final[tuple[Word, ...]] = _parse(_ADULTS)
